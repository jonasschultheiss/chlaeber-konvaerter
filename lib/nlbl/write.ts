import type { BarcodeSymbology, LabelObject, ParsedLabel } from "@/lib/types";
import { escapeXml, xmlHeader } from "@/lib/xml";

const NLBL_PASSWORD = ",^_A5Fus&!?j='Epiq*e";

configure({ useWebWorkers: false });

export async function writeNlbl(label: ParsedLabel): Promise<Uint8Array> {
  const formatId = randomUUID();
  const solutionId = randomUUID();
  const safeName = sanitizeFileStem(label.title || "label");
  const variables = label.objects.map((object, index) => ({
    object,
    variableId: randomUUID(),
    promptOrder: 1000 + index,
  }));

  const slnx = buildSlnx({
    solutionId,
    formatId,
    name: safeName,
    variables,
  });
  const format = buildFormat({
    formatId,
    name: safeName,
    widthMm: label.widthMm,
    heightMm: label.heightMm,
    printer: label.printer,
    variables,
  });

  const zipWriter = new ZipWriter(new Uint8ArrayWriter(), {
    password: NLBL_PASSWORD,
    encryptionStrength: 3,
    useWebWorkers: false,
  });

  await zipWriter.add(`${safeName}.slnx`, new TextReader(slnx));
  await zipWriter.add(`Formats/${safeName}`, new TextReader(format));
  return zipWriter.close();
}

type VariableBinding = {
  object: LabelObject;
  variableId: string;
  promptOrder: number;
};

