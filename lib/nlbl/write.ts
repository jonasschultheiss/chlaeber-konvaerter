function barcodeDataType(symbology: BarcodeSymbology): string {
  switch (symbology) {
    case "code128":
      return "Code128BarcodeData";
    case "code39":
      return "Code39BarcodeData";
    case "ean13":
      return "Ean13BarcodeData";
    case "qr":
      return "QrCodeBarcodeData";
    case "datamatrix":
      return "DataMatrixBarcodeData";
    default: {
      const exhaustive: never = symbology;
      return exhaustive;
    }
  }
}

function sanitizeFileStem(value: string): string {
  const cleaned = value.replaceAll(/[^\p{L}\p{N}_-]+/gu, "_").replaceAll(/^_+|_+$/g, "");
  return cleaned.slice(0, 60) || "label";
}
